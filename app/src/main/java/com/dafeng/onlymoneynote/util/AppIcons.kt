/**
 * 统一渲染分类图标。
 * - 普通 key（如 "restaurant"）→ 用 Material 矢量图标。
 * - emoji 前缀（"emoji:🍔"）→ 直接画文字 emoji，让用户能自定义任意表情。
 *
 * 全 App 所有分类图标都走这里，emoji 才能在列表/弹窗/记账页一致显示。
 */
@Composable
fun CategoryIcon(
    iconKey: String,
    size: Dp,
    modifier: Modifier = Modifier,
    tint: Color = LocalContentColor.current
) {
    if (iconKey.startsWith("emoji:")) {
        Box(modifier = modifier.size(size), contentAlignment = Alignment.Center) {
            Text(
                text = iconKey.removePrefix("emoji:"),
                fontSize = (size.value * 0.72f).sp,
                textAlign = TextAlign.Center,
                maxLines = 1
            )
        }
    } else {
        Icon(
            imageVector = AppIcons.get(iconKey),
            contentDescription = null,
            modifier = modifier.size(size),
            tint = tint
        )
    }
}
