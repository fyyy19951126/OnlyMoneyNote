    /**
     * 解析 colorKey（"#RRGGBB" 或 "#AARRGGBB"）为颜色。
     * 空串/非法 = null，调用方回退到分组色。
     */
    fun colorFromKey(key: String?): Color? {
        if (key.isNullOrBlank() || !key.startsWith("#")) return null
        val hex = key.removePrefix("#")
        return when (hex.length) {
            6 -> (hex.toLongOrNull(16))?.let { Color((0xFF000000L or it).toInt()) }
            8 -> (hex.toLongOrNull(16))?.let { Color(it.toInt()) }
            else -> null
        }
    }

    /** Color → colorKey 字符串（存库用） */
    fun colorToKey(color: Color): String =
        "#%08X".format((color.toArgb().toLong() and 0xFFFFFFFFL))

